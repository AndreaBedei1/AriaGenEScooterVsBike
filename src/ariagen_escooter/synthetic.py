# Generation
# --------------------------------------------------------------------------- #
def build_world(seed: int, speed_scale: float = 1.0) -> tuple[World, list[Fixation], np.random.Generator]:
    rng = np.random.default_rng(seed)
    route = _build_route(speed_scale)
    t, speed, heading, xy, arc = route
    objects = _objects(route)
    # lateral avoidance of the parked car (scooter path moves 0.6 m left around t = 75 s)
    bump = np.where((t > 72.5) & (t < 77.5), 0.5 * (1 - np.cos(2 * np.pi * (t - 72.5) / 5.0)), 0.0) * 0.6
    left = np.stack([-np.sin(heading), np.cos(heading)], axis=-1)
    riding = (t >= 25.0) & (t <= 134.5)
    sway = np.where(riding, 0.03 * np.sin(2 * np.pi * 0.9 * t), 0.0)
    head_xy = xy + (bump + sway)[:, None] * left
    head_z = HEAD_HEIGHT_M + np.where(riding, 0.01 * np.sin(2 * np.pi * 1.7 * t), 0.0)
    head_xyz = np.column_stack([head_xy, head_z])
    world = World(t, speed, heading, xy, arc, head_xyz, heading.copy(), np.full(t.size, np.radians(-8.0)), objects)
    schedule = _gaze_schedule(world, rng)

    # head follows large gaze shifts (gain 0.55 above 20 deg) with a first-order lag
    points, _, _ = _target_points(world, schedule, t)
    rel = np.arctan2(points[:, 1] - head_xyz[:, 1], points[:, 0] - head_xyz[:, 0]) - heading
    rel = (rel + np.pi) % (2 * np.pi) - np.pi
    desired = np.where(np.abs(rel) > np.radians(20), 0.55 * rel, 0.0)
    offset = np.zeros_like(desired)
    alpha = (1.0 / FINE_HZ) / 0.15
    for i in range(1, t.size):
        offset[i] = offset[i - 1] + alpha * (desired[i] - offset[i - 1])
    looking_down = ~riding & (
        np.degrees(np.arctan2(points[:, 2] - head_z, np.hypot(*(points[:, :2] - head_xy).T))) < -30
    )
    pitch_target = np.where(looking_down, np.radians(-35.0), np.radians(-8.0))
    pitch = np.zeros_like(pitch_target)
    pitch[0] = pitch_target[0]
    for i in range(1, t.size):
        pitch[i] = pitch[i - 1] + alpha * (pitch_target[i] - pitch[i - 1])
    jitter = np.zeros(t.size)
    for a, b in GLASSES_HANDLING:
        m = (t >= a) & (t <= b)
        jitter[m] = _smooth(rng.normal(0, 0.25, t.size), 0.3)[m]
    world.head_yaw = heading + offset + jitter
    world.head_pitch = pitch + 0.5 * jitter
    return world, schedule, rng


def generate_session(
    out_root: Path,
    *,
    participant_number: int = 1,
    session_number: int = 1,
    seed: int = 20261006,
    speed_scale: float = 1.0,
    taxonomy_names: tuple[str, ...],
) -> Path:
    """Write one synthetic session to ``out_root/<session_id>`` and return its path."""
    participant = make_participant_id(participant_number, synthetic=True)
    session_id = make_session_id(participant, session_number)
    recording_id = make_recording_id(session_id, 1)
    session_dir = out_root / session_id
    rec_dir = session_dir / recording_id
    world, schedule, rng = build_world(seed, speed_scale)
    class_ids = {name: i for i, name in enumerate(taxonomy_names)}

    def ns(times: np.ndarray) -> np.ndarray:
        return (T0_NS + np.round(np.asarray(times) * NS_PER_S)).astype(np.int64)

    # --- pose (20 Hz) ---------------------------------------------------------------
    tp = np.arange(0.0, DURATION_S + 1e-9, 1.0 / POSE_HZ)
    head = world.interp(world.head_xyz, tp) + rng.normal(0, 0.01, (tp.size, 3))
    yaw = np.interp(tp, world.t, np.unwrap(world.head_yaw))
    pitch = np.interp(tp, world.t, world.head_pitch)
    from ariagen_escooter.gaze import rotmat_to_quat

    quat = rotmat_to_quat(_rotation(yaw, pitch))
    pose = pd.DataFrame(
        {
            "t_ns": ns(tp),
            "x_m": head[:, 0],
            "y_m": head[:, 1],
            "z_m": head[:, 2],
            "qw": quat[:, 0],
            "qx": quat[:, 1],
            "qy": quat[:, 2],
            "qz": quat[:, 3],
        }
    )

    # --- IMU (50 Hz, simplified: IMU axes = CPF axes) ---------------------------------
    ti = np.arange(0.0, DURATION_S + 1e-9, 1.0 / IMU_HZ)
    dt = 1.0 / FINE_HZ
    acc_w = np.gradient(np.gradient(world.head_xyz, dt, axis=0), dt, axis=0)
    acc_w = np.stack([_smooth(acc_w[:, k], 0.1) for k in range(3)], axis=-1)
    acc_w[:, 2] += GRAVITY
    rot_fine = _rotation(np.unwrap(world.head_yaw), world.head_pitch)
    f_c = np.einsum("nji,nj->ni", rot_fine, acc_w)
    yaw_rate = np.gradient(np.unwrap(world.head_yaw), dt)
    pitch_rate = np.gradient(world.head_pitch, dt)
    omega_w = (
        np.stack([np.zeros_like(yaw_rate), np.zeros_like(yaw_rate), yaw_rate], axis=-1)
        - pitch_rate[:, None] * rot_fine[:, :, 0]
    )
    g_c = np.einsum("nji,nj->ni", rot_fine, omega_w)
    vib = (
        np.stack([_smooth(rng.normal(0, 1, world.t.size), 0.03) for _ in range(3)], axis=-1)
        * (0.12 * world.speed)[:, None]
    )
    imu_acc = np.stack([np.interp(ti, world.t, (f_c + vib)[:, k]) for k in range(3)], axis=-1) + rng.normal(
        0, 0.03, (ti.size, 3)
    )
    imu_gyr = np.stack([np.interp(ti, world.t, g_c[:, k]) for k in range(3)], axis=-1) + rng.normal(
        0, 0.005, (ti.size, 3)
    )
    imu = pd.DataFrame(
        {
            "t_ns": ns(ti),
            "accel_x_mps2": imu_acc[:, 0],
            "accel_y_mps2": imu_acc[:, 1],
            "accel_z_mps2": imu_acc[:, 2],
            "gyro_x_radps": imu_gyr[:, 0],
            "gyro_y_radps": imu_gyr[:, 1],
            "gyro_z_radps": imu_gyr[:, 2],
        }
    )

    # --- GPS (1 Hz, external logger, deliberate clock residual) -------------------------
    tg = np.arange(0.0, DURATION_S + 1e-9, 1.0 / GPS_HZ)
    route = world.interp(world.route_xy, tg)
    noise = np.zeros((tg.size, 2))
    for i in range(1, tg.size):
        noise[i] = 0.9 * noise[i - 1] + rng.normal(0, 0.9, 2)
    rot = np.radians(GPS_FRAME_ROTATION_DEG)
    gx = np.cos(rot) * route[:, 0] - np.sin(rot) * route[:, 1] + 120.0 + noise[:, 0]
    gy = np.sin(rot) * route[:, 0] + np.cos(rot) * route[:, 1] - 80.0 + noise[:, 1]
    lat, lon = local_xy_to_latlon(gx, gy, *GPS_ORIGIN)
    gps = pd.DataFrame(
        {
            "t_ns": ns(tg + GPS_CLOCK_RESIDUAL_S),
            "lat_deg": lat,
            "lon_deg": lon,
            "accuracy_m": 3.0 + np.abs(rng.normal(0, 1.0, tg.size)),
            "speed_mps": np.clip(np.interp(tg, world.t, world.speed) + rng.normal(0, 0.15, tg.size), 0, None),
        }
    )

    # --- frames (10 Hz) and label maps -----------------------------------------------------
    tf = np.arange(0.0, DURATION_S + 1e-9, 1.0 / FRAME_HZ) + 0.007
    tf = tf[tf <= DURATION_S]
    keep = np.ones(tf.size, dtype=bool)
    keep[list(DROPPED_FRAMES)] = False
    frame_idx = np.arange(tf.size)[keep]
    frames = pd.DataFrame({"t_ns": ns(tf[keep]), "frame_index": frame_idx, "width_px": IMAGE_W, "height_px": IMAGE_H})
    rendered = [_render(world, float(tf[k]), class_ids) for k in frame_idx]
    store = LabelMapStore(
        frame_idx,
        np.stack([r[0] for r in rendered]),
        taxonomy_names,
        (IMAGE_W, IMAGE_H),
        "synthetic_renderer",
        np.stack([r[1] for r in rendered]),
    )

    # --- gaze (30 Hz) -----------------------------------------------------------------------
    tz = np.arange(0.0, DURATION_S + 1e-9, 1.0 / GAZE_HZ)
    tz_jit = tz + rng.normal(0, 0.001, tz.size)
    points, target_instance, _ = _target_points(world, schedule, tz)
    head_z = world.interp(world.head_xyz, tz)
    rot_z = _rotation(np.interp(tz, world.t, np.unwrap(world.head_yaw)), np.interp(tz, world.t, world.head_pitch))
    d_w = points - head_z
    d_w /= np.linalg.norm(d_w, axis=-1, keepdims=True)
    d_c = np.einsum("nji,nj->ni", rot_z, d_w)
    behind = d_c[:, 2] < 0.05
    d_c[behind, 2] = 0.05
    gaze_yaw = np.clip(np.arctan2(d_c[:, 0], d_c[:, 2]), np.radians(-50), np.radians(50))
    gaze_pitch = np.clip(np.arctan2(d_c[:, 1], d_c[:, 2]), np.radians(-40), np.radians(40))
    gaze_yaw += np.radians(rng.normal(0, 0.3, tz.size))
    gaze_pitch += np.radians(rng.normal(0, 0.3, tz.size))
    valid = np.ones(tz.size, dtype=bool)
    protected = np.zeros(tz.size, dtype=bool)
    for fix in schedule:
        if fix.scripted:
            protected |= (tz >= fix.t_start - 0.3) & (tz <= fix.t_start + 0.4)
    t_blink = rng.exponential(3.5)
    while t_blink < DURATION_S:
        blink = (tz >= t_blink) & (tz <= t_blink + rng.uniform(0.1, 0.2))
        if not (blink & protected).any():
            valid &= ~blink
        t_blink += rng.exponential(3.5)
    for a, b in TRACKING_LOSS + GLASSES_HANDLING:
        valid &= ~((tz >= a) & (tz <= b))
    confidence = np.where(valid, np.clip(rng.normal(0.93, 0.03, tz.size), 0, 1), np.nan)
    u_px = CX - FOCAL_PX * np.tan(gaze_yaw)
    v_px = CY - FOCAL_PX * np.tan(gaze_pitch)
    gaze = pd.DataFrame(
        {
            "t_ns": ns(tz_jit),
            "valid": valid,
            "yaw_rad": np.where(valid, gaze_yaw, np.nan),
            "pitch_rad": np.where(valid, gaze_pitch, np.nan),
            "u_px": np.where(valid, u_px, np.nan),
            "v_px": np.where(valid, v_px, np.nan),
            "confidence": confidence,
        }
    )

    # --- annotations -----------------------------------------------------------------------------
    segments = pd.DataFrame(
        [
            {
                "segment_id": f"{recording_id}_SEG{i + 1:03d}",
                "t_start_ns": int(ns(a)),
                "t_end_ns": int(ns(b)),
                "infrastructure_class": cls,
                "source": "synthetic",
                "annotator": "SYNTH",
                "notes": "synthetic",
            }
            for i, (a, b, cls) in enumerate(SEGMENTS)
        ]
    )
    event_rows = [
        (42.0, 52.0, 49.0, "pedestrian_interaction", "", "pedestrian", 1, "pedestrian crosses the cycle path"),
        (58.0, 68.0, None, "crossing", "", "", 0, "crossing with stop"),
        (61.0, 65.0, None, "stopping", "", "", 0, "stop before the crossing"),
        (71.0, 77.5, 75.0, "parked_vehicle", "", "parked_vehicle", 3, "parked car narrows the road"),
        (78.5, 86.0, 80.3, "vehicle_interaction", "overtaking", "car", 2, "rider overtaken by a car"),
        (90.0, 106.5, 93.1, "roundabout", "vehicle_interaction", "car", 9, "car crossing at roundabout entry"),
        (113.0, 121.0, 115.6, "cyclist_interaction", "overtaking", "cyclist", 4, "rider overtaken by a cyclist"),
        (
            121.0,
            128.0,
            126.0,
            "pedestrian_interaction",
            "",
            "pedestrian",
            0,
            "pedestrians walking ahead on shared path",
        ),
    ]
    events = pd.DataFrame(
        [
            {
                "event_id": f"{recording_id}_EV{i + 1:03d}",
                "t_start_ns": int(ns(a)),
                "t_end_ns": int(ns(b)),
                "t_reference_ns": int(ns(r)) if r is not None else None,
                "event_type": et,
                "tags": tags,
                "target_class": tc,
                "target_instance_id": ti_ if ti_ else None,
                "source": "synthetic",
                "annotator": "SYNTH",
                "notes": note,
            }
            for i, (a, b, r, et, tags, tc, ti_, note) in enumerate(event_rows)
        ]
    )
    events["t_reference_ns"] = events["t_reference_ns"].astype("Int64")
    events["target_instance_id"] = events["target_instance_id"].astype("Int64")

    # --- ground truth -----------------------------------------------------------------------------------
    accel_true = np.gradient(world.speed, 1.0 / FINE_HZ)
    moving = world.speed > 2.0
    first_gaze = {}
    for i, (a, b, r, _event_type, _tags, tc, ti_, note) in enumerate(event_rows):
        eid = f"{recording_id}_EV{i + 1:03d}"
        fix = [
            f
            for f in schedule
            if f.scripted
            and f.kind == "object"
            and a - 5.0 <= f.t_start <= b
            and (
                f.instance_id == ti_
                or (not ti_ and any(o.instance_id == f.instance_id and o.semantic == tc for o in world.objects))
            )
        ]
        onset = None
        start_search = fix[0].t_start if fix else a - 5.0
        decel = (world.t >= start_search) & (world.t <= b + 3.0) & (accel_true <= -0.5)
        if decel.any():
            onset = float(world.t[np.flatnonzero(decel)[0]])
        first_gaze[eid] = {
            "first_gaze_rel_s": fix[0].t_start if fix else None,
            "action_onset_rel_s": onset,
            "reference_rel_s": r,
            "notes": note,
        }
    ground_truth = {
        "notice": SYNTHETIC_NOTICE,
        "seed": seed,
        "speed_scale": speed_scale,
        "device_time_origin_ns": T0_NS,
        "riding": {
            "motion_start_rel_s": 25.0,
            "motion_end_rel_s": 134.5,
            "speed_above_2mps_first_rel_s": float(world.t[np.flatnonzero(moving & (world.t > 22))[0]]),
            "speed_above_2mps_last_rel_s": float(world.t[np.flatnonzero(moving)[-1]]),
        },
        "gps_clock_residual_s": GPS_CLOCK_RESIDUAL_S,
        "expected_gps_offset_correction_s": -GPS_CLOCK_RESIDUAL_S,
        "dropped_frames": list(DROPPED_FRAMES),
        "tracking_loss_rel_s": [list(x) for x in TRACKING_LOSS],
        "glasses_handling_rel_s": [list(x) for x in GLASSES_HANDLING],
        "events": first_gaze,
        "simplifications": [
            "ideal pinhole camera at the CPF (not Aria's fisheye RGB camera)",
            "IMU axes equal to CPF axes; no sensor biases",
            "no VIO drift; GPS noise is an AR(1) process",
        ],
    }

    manifest = {
        "manifest_version": 2,
        "synthetic": True,
        "participant_id": participant,
        "session_id": session_id,
        "protocol_version": "synthetic-0.1",
        "route": {
            "route_id": "SYNTHETIC_ROUTE_A",
            "variant": None,
            "description": "Procedural synthetic route - not a real place.",
        },
        "timing": {"date": None, "start_time_local": None, "timezone": None},
        "conditions": {
            "weather": "dry",
            "road_surface": "dry",
            "light": "daylight",
            "traffic_density": "medium",
            "temperature_c": None,
            "notes": SYNTHETIC_NOTICE,
        },
        "equipment": {
            "aria_device_code": "SYNTHETIC",
            "recording_profile": "synthetic",
            "vehicles": [
                {
                    "vehicle_code": "SYN_ESC",
                    "vehicle_type": "escooter",
                    "model": None,
                    "characteristics": {},
                    "notes": SYNTHETIC_NOTICE,
                }
            ],
            "external_gps_logger": "SYNTHETIC",
        },
        "recordings": [
            {
                "recording_id": recording_id,
                "trial": {
                    "vehicle_type": "escooter",
                    "vehicle_code": "SYN_ESC",
                    "trial_number": 1,
                    "ride_order": 1,
                    "part": 1,
                    "route_id": None,
                    "route_direction": None,
                    "rider_reported_issues": "",
                },
                "files": {"vrs": None, "mps_dir": None, "external_gps": None},
                "streams": {
                    "rgb": "available",
                    "eye_gaze": "available",
                    "imu": "available",
                    "pose": "available",
                    "gps_device": "missing",
                    "gps_phone": "missing",
                    "gps_external": "available",
                    "mps_slam": "missing",
                    "mps_eye_gaze": "missing",
                },
                "clock": {
                    "external_gps_offset_ns": 0,
                    "method": "synthetic: GPS already in device time with a deliberate +0.6 s residual",
                    "uncertainty_s": 1.0,
                },
                "device_time_start_ns": int(T0_NS),
                "device_time_end_ns": int(ns(DURATION_S)),
                "trimming_override": None,
                "notes": SYNTHETIC_NOTICE,
                "technical_issues": [
                    {
                        "description": "simulated tracking loss 98.0-99.5 s and three dropped RGB frames",
                        "severity": "minor",
                        "streams": ["eye_gaze", "rgb"],
                    }
                ],
            }
        ],
        "notes": SYNTHETIC_NOTICE,
        "technical_issues": [],
    }

    write_yaml(manifest, session_dir / "manifest.yaml")
    decimals = {"pose": 4, "imu": 4, "gps": 7, "gaze": 6, "frames": 0}
    for name, df in (("pose", pose), ("imu", imu), ("gps", gps), ("gaze", gaze), ("frames", frames)):
        write_csv(df, rec_dir / "streams" / f"{name}.csv", decimals[name] or 1)
    write_csv(segments, rec_dir / "annotations" / "segments.csv")
    write_csv(events, rec_dir / "annotations" / "events.csv")
    store.save(rec_dir / "semantic" / "labels.npz")
    write_json(ground_truth, session_dir / "ground_truth.json", 6)
    (session_dir / "README.md").write_text(_readme(session_id, seed, speed_scale), encoding="utf-8", newline="\n")
    return session_dir


