def _gaze_schedule(world: World, rng: np.random.Generator) -> list[Fixation]:
    scripted = []
    for start, end, kind, target in SCRIPTED:
        if kind == "object":
            scripted.append(Fixation(start, end, "object", instance_id=int(target), scripted=True))
        else:
            scripted.append(Fixation(start, end, "direction", rel_az_deg=target[0], el_deg=target[1], scripted=True))
    saccade = 1.0 / GAZE_HZ  # one sample of transition between fixations
    schedule: list[Fixation] = []
    cursor = 0.0
    for fix in scripted + [Fixation(DURATION_S, DURATION_S, "point")]:
        while cursor < fix.t_start - 0.15:
            duration = min(0.12 + rng.gamma(3.0, 0.12), fix.t_start - cursor)
            if duration < 0.1:
                break
            schedule.append(_default_fixation(world, rng, cursor, cursor + duration))
            cursor += duration + saccade
        # stretch the last free fixation so that saccades stay one sample long
        if schedule and not schedule[-1].scripted and schedule[-1].t_end < fix.t_start - saccade:
            schedule[-1] = replace(schedule[-1], t_end=fix.t_start - saccade)
        if fix.t_end > fix.t_start:
            schedule.append(fix)
            cursor = fix.t_end + saccade
    return schedule


def _default_fixation(world: World, rng: np.random.Generator, start: float, end: float) -> Fixation:
    speed = float(np.interp(start, world.t, world.speed))
    riding = 25.0 <= start <= 134.5
    if not riding:
        visible = [o for o in world.objects if o.instance_id in (10, 11) and o.t_visible[0] <= start <= o.t_visible[1]]
        u = rng.random()
        if visible and u < 0.4:
            return Fixation(start, end, "object", instance_id=visible[0].instance_id)
        if u < 0.7:
            return Fixation(start, end, "direction", rel_az_deg=float(rng.normal(0, 10)), el_deg=-50.0)
        return Fixation(
            start,
            end,
            "direction",
            rel_az_deg=float(rng.choice([-1, 1]) * rng.uniform(20, 60)),
            el_deg=float(rng.uniform(-5, 15)),
        )
    s_now = world.arc_at(start)
    u = rng.random()
    if u < 0.6:
        ahead, lateral = rng.uniform(10, 25), rng.normal(0, 0.5)
    elif u < 0.75:
        ahead, lateral = rng.uniform(4, 8), rng.normal(0, 0.4)
    elif u < 0.85:
        ahead, lateral = rng.uniform(5, 12), float(rng.choice([-1, 1]) * rng.uniform(1.3, 2.5))
    else:
        return Fixation(
            start,
            end,
            "direction",
            rel_az_deg=float(rng.choice([-1, 1]) * rng.uniform(30, 60)),
            el_deg=float(rng.uniform(0, 15)),
        )
    ahead = ahead * max(speed, 1.0) / 4.5
    p, psi = world.route_at_arc(np.array([s_now + ahead]))
    point = (float(p[0, 0] - lateral * np.sin(psi[0])), float(p[0, 1] + lateral * np.cos(psi[0])), 0.0)
    return Fixation(start, end, "point", point=point)


def _target_points(
    world: World, schedule: list[Fixation], times: np.ndarray
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """World target point per time, plus target instance id and validity mask."""
    points = np.full((times.size, 3), np.nan)
    instance = np.zeros(times.size, dtype=np.int64)
    by_id = {o.instance_id: o for o in world.objects}
    starts = np.array([f.t_start for f in schedule])
    k = np.searchsorted(starts, times, side="right") - 1
    for i, fix in enumerate(schedule):
        sel = (k == i) & (times <= fix.t_end)
        if not sel.any():
            continue
        if fix.kind == "object":
            obj = by_id[fix.instance_id]
            xy = obj.position(times[sel])
            points[sel] = np.column_stack([xy, np.full(sel.sum(), 0.75 * obj.height_m)])
            instance[sel] = fix.instance_id
        elif fix.kind == "point":
            points[sel] = fix.point
        else:
            head = world.interp(world.head_xyz, np.array([fix.t_start]))[0]
            psi = float(np.interp(fix.t_start, world.t, world.heading)) + np.radians(fix.rel_az_deg)
            el = np.radians(fix.el_deg)
            direction = np.array([np.cos(el) * np.cos(psi), np.cos(el) * np.sin(psi), np.sin(el)])
            points[sel] = head + 30.0 * direction
    # saccades: samples between fixations aim halfway between neighbours
    missing = ~np.isfinite(points[:, 0])
    if missing.any():
        good = np.flatnonzero(~missing)
        for col in range(3):
            points[missing, col] = np.interp(np.flatnonzero(missing), good, points[good, col])
    return points, instance, ~missing


