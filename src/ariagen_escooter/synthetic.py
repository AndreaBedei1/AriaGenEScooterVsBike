def _segment_class_at_time(times: np.ndarray) -> np.ndarray:
    out = np.full(times.shape, "plaza", dtype=object)
    for start, end, cls in SEGMENTS:
        out[(times >= start) & (times < end)] = cls
    return out


def _render(world: World, time_s: float, class_ids: dict[str, int]) -> tuple[np.ndarray, np.ndarray]:
    jj, ii = np.meshgrid(np.arange(MAP_W), np.arange(MAP_H))
    u = (jj + 0.5) * IMAGE_W / MAP_W - 0.5  # full-resolution coordinates of label-pixel centres
    v = (ii + 0.5) * IMAGE_H / MAP_H - 0.5
    d_c = np.stack([-(u - CX) / FOCAL_PX, -(v - CY) / FOCAL_PX, np.ones_like(u)], axis=-1)
    d_c /= np.linalg.norm(d_c, axis=-1, keepdims=True)
    head = world.interp(world.head_xyz, np.array([time_s]))[0]
    yaw = float(np.interp(time_s, world.t, world.head_yaw))  # continuous by construction (no wrapping)
    pitch = float(np.interp(time_s, world.t, world.head_pitch))
    rot = _rotation(np.array([yaw]), np.array([pitch]))[0]
    d_w = d_c @ rot.T
    labels = np.full((MAP_H, MAP_W), class_ids["sky"], dtype=np.uint8)
    instances = np.zeros((MAP_H, MAP_W), dtype=np.uint8)
    depth = np.full((MAP_H, MAP_W), np.inf)

    s_now = world.arc_at(time_s)
    p_now, psi_now = world.route_at_arc(np.array([s_now]))
    ground = d_w[..., 2] < -1e-6
    s_hit = np.where(ground, -head[2] / np.where(ground, d_w[..., 2], -1.0), 0.0)
    gx, gy = head[0] + s_hit * d_w[..., 0], head[1] + s_hit * d_w[..., 1]
    tx, ty = np.cos(psi_now[0]), np.sin(psi_now[0])
    forward = (gx - p_now[0, 0]) * tx + (gy - p_now[0, 1]) * ty
    lateral = -(gx - p_now[0, 0]) * ty + (gy - p_now[0, 1]) * tx
    ground_time = world.time_at_arc(s_now + np.where(ground, forward, 0.0))
    seg_class = _segment_class_at_time(np.where(ground, ground_time, time_s))
    for profile_name, bands in PROFILES.items():
        in_profile = ground & (seg_class == profile_name)
        if not in_profile.any():
            continue
        for lo, hi, cls in bands:
            labels[in_profile & (lateral >= lo) & (lateral < hi)] = class_ids[cls]
    zebra_start = world.arc_at(61.5) + 0.5
    on_zebra = (
        ground & (np.abs(lateral) <= 3.0) & (s_now + forward >= zebra_start) & (s_now + forward <= zebra_start + 6.0)
    )
    labels[on_zebra] = class_ids["crossing"]
    depth[ground] = s_hit[ground]

    sky = ~ground
    rel_az = np.degrees(np.arctan2(-d_w[..., 0] * ty + d_w[..., 1] * tx, d_w[..., 0] * tx + d_w[..., 1] * ty))
    elev = np.degrees(np.arcsin(np.clip(d_w[..., 2], -1, 1)))
    current = _segment_class_at_time(np.array([time_s]))[0]
    if current in PARK_LIKE:
        labels[sky & (np.abs(rel_az) > 15) & (elev < 12)] = class_ids["vegetation"]
    else:
        labels[sky & (np.abs(rel_az) > 30) & (elev < 25)] = class_ids["building"]
        if current == "roundabout":
            labels[sky & (rel_az > 20) & (elev < 10)] = class_ids["vegetation"]

    for obj in world.objects:
        if not (obj.t_visible[0] <= time_s <= obj.t_visible[1]):
            continue
        centre = obj.position(np.array([time_s]))[0]
        n = head[:2] - centre
        dist = float(np.linalg.norm(n))
        if dist < 0.3:
            continue
        n /= dist
        denom = d_w[..., 0] * n[0] + d_w[..., 1] * n[1]
        with np.errstate(divide="ignore", invalid="ignore"):
            s_obj = ((centre[0] - head[0]) * n[0] + (centre[1] - head[1]) * n[1]) / denom
        hx, hy, hz = head[0] + s_obj * d_w[..., 0], head[1] + s_obj * d_w[..., 1], head[2] + s_obj * d_w[..., 2]
        along = (hx - centre[0]) * (-n[1]) + (hy - centre[1]) * n[0]
        hit = (s_obj > 0) & (np.abs(along) <= obj.width_m / 2) & (hz >= 0) & (hz <= obj.height_m) & (s_obj < depth)
        labels[hit] = class_ids[obj.semantic]
        instances[hit] = obj.instance_id
        depth[hit] = s_obj[hit]
    return labels, instances


